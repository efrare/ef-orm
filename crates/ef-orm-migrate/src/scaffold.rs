//! Rust entity scaffolding from a live schema (`ef-orm-cli scaffold`).

use crate::introspect::{LiveColumn, LiveSchema, LiveTable};
use ef_orm_query::SqlType;

/// Generates `#[derive(Entity, Model)]` structs for every table in `schema`.
///
/// The output is a starting point: review column names/types, add module
/// attributes and pick the right chrono/uuid/decimal features before use.
pub fn scaffold(schema: &LiveSchema) -> String {
    let mut source = String::new();
    source.push_str("// Generated by ef-orm-cli scaffold — review before committing.\n");
    source.push_str("use ef_orm::{Entity, Model};\n");

    for table in &schema.tables {
        source.push('\n');
        write_table(&mut source, table);
    }
    source
}

fn write_table(source: &mut String, table: &LiveTable) {
    let struct_name = pascal_case(&table.name);
    source.push_str("#[derive(Entity, Model)]\n");
    source.push_str(&format!("#[orm(table = \"{}\")]\n", table.name));
    source.push_str(&format!("pub struct {struct_name} {{\n"));

    for column in &table.columns {
        if column.primary_key {
            source.push_str(if column.identity {
                "    #[orm(primary_key, auto)]\n"
            } else {
                "    #[orm(primary_key)]\n"
            });
        }
        source.push_str(&format!(
            "    pub {}: {},\n",
            column.name,
            rust_type(column)
        ));
    }
    source.push_str("}\n");
}

/// Maps a portable [`SqlType`] to the Rust type the facade maps it back to.
fn rust_type(column: &LiveColumn) -> String {
    let base = match &column.ty {
        SqlType::Int => "i32",
        SqlType::BigInt => "i64",
        SqlType::SmallInt => "i16",
        SqlType::TinyInt => "u8",
        SqlType::Bit => "bool",
        SqlType::Float => "f64",
        SqlType::Real => "f32",
        SqlType::Decimal { .. } => "rust_decimal::Decimal",
        SqlType::UniqueIdentifier => "uuid::Uuid",
        SqlType::Date
        | SqlType::DateTime
        | SqlType::DateTime2
        | SqlType::DateTimeOffset
        | SqlType::Time => "chrono::NaiveDateTime",
        SqlType::VarBinary(_) | SqlType::VarBinaryMax | SqlType::Binary(_) => "Vec<u8>",
        SqlType::NVarChar(_)
        | SqlType::NVarCharMax
        | SqlType::VarChar(_)
        | SqlType::VarCharMax
        | SqlType::Char(_)
        | SqlType::NChar(_) => "String",
    };
    if column.nullable {
        format!("Option<{base}>")
    } else {
        base.to_string()
    }
}

/// `order_items` → `OrderItems` (non-alphanumerics split words).
fn pascal_case(name: &str) -> String {
    let mut out = String::new();
    for part in name.split(|character: char| !character.is_alphanumeric()) {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    if out.is_empty() {
        "Entity".to_string()
    } else {
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn schema() -> LiveSchema {
        LiveSchema {
            tables: vec![LiveTable {
                name: "order_items".into(),
                columns: vec![
                    LiveColumn {
                        name: "id".into(),
                        ty: SqlType::Int,
                        nullable: false,
                        primary_key: true,
                        identity: true,
                    },
                    LiveColumn {
                        name: "sku".into(),
                        ty: SqlType::NVarChar(50),
                        nullable: false,
                        primary_key: false,
                        identity: false,
                    },
                    LiveColumn {
                        name: "price".into(),
                        ty: SqlType::Decimal {
                            precision: 18,
                            scale: 2,
                        },
                        nullable: true,
                        primary_key: false,
                        identity: false,
                    },
                ],
            }],
        }
    }

    #[test]
    fn scaffolds_a_derive_model_with_key_and_option_types() {
        let source = scaffold(&schema());

        assert!(source.contains("#[derive(Entity, Model)]"));
        assert!(source.contains("#[orm(table = \"order_items\")]"));
        assert!(source.contains("pub struct OrderItems {"));
        assert!(source.contains("    #[orm(primary_key, auto)]\n    pub id: i32,"));
        assert!(source.contains("    pub sku: String,"));
        assert!(source.contains("    pub price: Option<rust_decimal::Decimal>,"));
    }

    #[test]
    fn pascal_case_splits_on_non_alphanumerics() {
        assert_eq!(pascal_case("order_items"), "OrderItems");
        assert_eq!(pascal_case("users"), "Users");
        assert_eq!(pascal_case(""), "Entity");
    }
}
