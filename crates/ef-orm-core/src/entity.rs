//! Static entity metadata (phase 3).
//!
//! `#[derive(Entity)]` / `#[derive(Model)]` in `ef-orm-derive` implement these
//! traits from a user struct; the facade (`DbContext`/`DbSet`) consumes them
//! to build statements. Nothing here knows about SQL, drivers or async — the
//! query crate owns statements, the driver crate owns rows.

use crate::{OrmError, Value};

/// A type usable as a primary-key value: owned, cloneable and bindable.
///
/// Blanket-implemented for every `Into<Value> + Clone + Send + Sync` type
/// (`i32`, `String`, `uuid::Uuid`…), so `find`/`delete` accept the key by
/// value with full type checking.
pub trait PrimaryKey: Into<Value> + Clone + Send + Sync + 'static {}

impl<T> PrimaryKey for T where T: Into<Value> + Clone + Send + Sync + 'static {}

/// Static metadata of a mapped table.
///
/// All information is compile-time constants produced by `#[derive(Entity)]`;
/// the facade turns [`Entity::TABLE`] / [`Entity::SCHEMA`] into a query `Table`
/// and [`Entity::COLUMNS`] into the column list of `SELECT`/`INSERT`.
pub trait Entity: Send + Sync + 'static {
    /// Table name, without schema.
    const TABLE: &'static str;
    /// Schema qualifier; `None` defers to the dialect default (`dbo`).
    const SCHEMA: Option<&'static str> = None;
    /// Column names in declaration order (projection / insert lists).
    const COLUMNS: &'static [&'static str];
    /// Primary-key column. Phase 3 supports a single-column key only.
    const PRIMARY_KEY: &'static str;
    /// The key is `IDENTITY`: omitted from `INSERT`, filled back from
    /// `OUTPUT INSERTED.<pk>` via [`Model::set_id`].
    const PRIMARY_KEY_AUTO: bool = false;
    /// Rust type of the primary-key value.
    type Id: PrimaryKey;
    /// Typed column references used by the fluent `filter`/`order_by` API
    /// (generated as `{Struct}Columns`).
    type Columns;
    /// Builds the typed column references (cheap: plain data).
    fn columns() -> Self::Columns;
}

/// A mapped row instance: identity plus row ⇄ struct conversion.
///
/// The `Row → struct` half is generated by `#[derive(Model)]` as an impl of
/// the driver's `FromRow` trait (re-exported as `ef_orm::FromRow`), because
/// rows are a transport concern this crate must not depend on.
pub trait Model: Entity {
    /// Column/value pairs in declaration order, ready for `INSERT`.
    ///
    /// Auto-increment keys are omitted (the server generates them); other
    /// keys are included. `DbSet::update` drops [`Entity::PRIMARY_KEY`] from
    /// this list to build `SET`.
    fn to_values(&self) -> Vec<(&'static str, Value)>;
    /// The current primary-key value.
    fn id(&self) -> Self::Id;
    /// Writes back a server-generated key after an identity `INSERT`.
    ///
    /// The value comes from `OUTPUT INSERTED.<pk>` as a portable [`Value`];
    /// a wrong shape surfaces as [`OrmError::Conversion`].
    fn set_id(&mut self, id: Value) -> Result<(), OrmError>;
}

/// A reference to one column of an entity, typed by the Rust type it maps to.
///
/// Implemented by the generated column structs over `ColumnRef<T>`; the bound
/// is what lets `DbSet::select().order_by(c.age, …)` accept only real columns.
pub trait Column: Copy + Send + Sync {
    /// The column's SQL name (unquoted; the dialect quotes it).
    fn name(&self) -> &'static str;
}

#[cfg(test)]
mod tests {
    use super::{Column, Entity, Model, PrimaryKey};
    use crate::{OrmError, Value};

    /// Hand-written impls mirroring what the derive emits for:
    /// `#[derive(Entity, Model)] struct User { #[orm(primary_key, auto)] id: i32, name: String }`
    struct User {
        id: i32,
        name: String,
    }

    #[derive(Clone, Copy)]
    struct UserColumns {
        id: ColumnStub<i32>,
        name: ColumnStub<String>,
    }

    struct ColumnStub<T>(&'static str, std::marker::PhantomData<fn() -> T>);

    // Manual impls: `#[derive]` would demand `T: Copy` for no reason.
    impl<T> Clone for ColumnStub<T> {
        fn clone(&self) -> Self {
            *self
        }
    }
    impl<T> Copy for ColumnStub<T> {}

    impl<T> Column for ColumnStub<T> {
        fn name(&self) -> &'static str {
            self.0
        }
    }

    impl Entity for User {
        const TABLE: &'static str = "users";
        const COLUMNS: &'static [&'static str] = &["id", "name"];
        const PRIMARY_KEY: &'static str = "id";
        const PRIMARY_KEY_AUTO: bool = true;
        type Id = i32;
        type Columns = UserColumns;

        fn columns() -> Self::Columns {
            UserColumns {
                id: ColumnStub("id", std::marker::PhantomData),
                name: ColumnStub("name", std::marker::PhantomData),
            }
        }
    }

    impl Model for User {
        fn to_values(&self) -> Vec<(&'static str, Value)> {
            // Auto key omitted — the server fills it.
            vec![("name", self.name.clone().into())]
        }

        fn id(&self) -> Self::Id {
            self.id
        }

        fn set_id(&mut self, id: Value) -> Result<(), OrmError> {
            self.id = match id {
                Value::Int(v) => i32::try_from(v)
                    .map_err(|_| OrmError::Conversion(format!("{v} out of range for i32")))?,
                other => {
                    return Err(OrmError::Conversion(format!(
                        "expected integer id, found {other:?}"
                    )));
                }
            };
            Ok(())
        }
    }

    #[test]
    fn primary_key_is_blanket_for_bindable_owned_types() {
        fn assert_pk<T: PrimaryKey>() {}
        assert_pk::<i32>();
        assert_pk::<String>();
        assert_pk::<i64>();
    }

    #[test]
    fn entity_metadata_is_static_and_consistent() {
        assert_eq!(User::TABLE, "users");
        assert_eq!(User::SCHEMA, None);
        assert_eq!(User::COLUMNS, &["id", "name"]);
        assert_eq!(User::PRIMARY_KEY, "id");
        // Validated at compile time: metadata is all `const`.
        const {
            assert!(User::PRIMARY_KEY_AUTO);
        }
    }

    #[test]
    fn model_maps_values_and_writes_the_identity_back() {
        let mut user = User {
            id: 0,
            name: "ada".into(),
        };

        assert_eq!(user.to_values(), vec![("name", Value::Str("ada".into()))]);
        assert_eq!(user.id(), 0);

        user.set_id(Value::Int(7)).unwrap();
        assert_eq!(user.id(), 7);
        assert!(matches!(
            user.set_id(Value::Str("x".into())),
            Err(OrmError::Conversion(_))
        ));
    }

    #[test]
    fn typed_columns_expose_their_names() {
        let columns = User::columns();
        assert_eq!(columns.id.name(), "id");
        assert_eq!(columns.name.name(), "name");
    }
}
