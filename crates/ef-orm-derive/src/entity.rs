//! Code generation for `#[derive(Entity)]`.

use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use syn::{DeriveInput, LitStr, Type};

use crate::attrs;

/// Emits `{Struct}Columns` (typed column refs) + the `Entity` impl.
pub(crate) fn expand(input: &DeriveInput) -> syn::Result<TokenStream> {
    let name = &input.ident;
    let vis = &input.vis;
    let sattrs = attrs::parse_struct(&input.attrs)?;
    let table = sattrs.table.ok_or_else(|| {
        syn::Error::new(
            name.span(),
            "#[derive(Entity)] requires #[orm(table = \"…\")] naming the SQL table",
        )
    })?;
    let fields = attrs::field_infos(input)?;
    if fields.is_empty() {
        return Err(syn::Error::new(
            name.span(),
            "#[derive(Entity)] needs at least one column field",
        ));
    }
    let primary = attrs::require_primary_key(input, &fields)?;

    let columns_struct = format_ident!("{name}Columns");
    let table = LitStr::new(&table, name.span());
    let schema = match &sattrs.schema {
        Some(schema) => {
            let schema = LitStr::new(schema, name.span());
            quote!(::core::option::Option::Some(#schema))
        }
        None => quote!(::core::option::Option::None),
    };
    let primary_name = LitStr::new(&primary.name, name.span());
    let primary_ty: &Type = primary.ty;
    let primary_auto = primary.attrs.auto;

    let idents: Vec<_> = fields.iter().map(|field| field.ident).collect();
    let column_names: Vec<_> = fields
        .iter()
        .map(|field| LitStr::new(&field.name, name.span()))
        .collect();
    let types: Vec<&Type> = fields.iter().map(|field| field.ty).collect();
    let columns_doc =
        format!("Typed column references of [`{name}`] (generated by `#[derive(Entity)]`).");

    Ok(quote! {
        #[doc = #columns_doc]
        #[derive(Clone, Copy)]
        #vis struct #columns_struct {
            #(pub #idents: ::ef_orm::ColumnRef<#types>,)*
        }

        impl ::ef_orm::Entity for #name {
            const TABLE: &'static str = #table;
            const SCHEMA: ::core::option::Option<&'static str> = #schema;
            const COLUMNS: &'static [&'static str] = &[#(#column_names),*];
            const PRIMARY_KEY: &'static str = #primary_name;
            const PRIMARY_KEY_AUTO: bool = #primary_auto;
            type Id = #primary_ty;
            type Columns = #columns_struct;

            fn columns() -> Self::Columns {
                #columns_struct {
                    #(#idents: ::ef_orm::ColumnRef::new(#column_names),)*
                }
            }
        }
    })
}
